    public static List<Entry> entries() { return ENTRIES; }
    public static Set<String> groups(GolemLegacyItem item) {
        var result=new HashSet<String>();
        for(var e:ENTRIES) if(e.item.equals(item.id()) && (e.metadata==GolemLegacyItem.WILDCARD || e.metadata==item.metadata())) result.add(e.group);
        return Set.copyOf(result);
    }
    /** Only previously audited exact common categories; aggregate tags never become ore equivalence. */
    public static Map<String,String> commonTags() {
        var tags=new HashSet<>(LegacyOreAspectTable.modernTagNames()); tags.addAll(LegacyOreDictionaryScans.modernTagNames());
        var result=new HashMap<String,String>();
        var prefixes=Map.of("ores","ore","ingots","ingot","dusts","dust","gems","gem","storage_blocks","block","plates","plate");
        for(var tag:tags) {
            var path=tag.substring(tag.indexOf(':')+1).split("/"); if(path.length!=2 || !prefixes.containsKey(path[0])) continue;
            var group=new StringBuilder(prefixes.get(path[0]));
            for(var word:path[1].split("_")) group.append(Character.toUpperCase(word.charAt(0))).append(word.substring(1));
            result.put(tag,group.toString());
        }
        result.putAll(Map.ofEntries(Map.entry("minecraft:logs","logWood"),Map.entry("minecraft:planks","plankWood"),
                Map.entry("minecraft:wooden_slabs","slabWood"),Map.entry("minecraft:wooden_stairs","stairWood"),
                Map.entry("minecraft:wooden_fences","fenceWood"),Map.entry("minecraft:wooden_doors","doorWood"),
                Map.entry("minecraft:saplings","treeSapling"),Map.entry("minecraft:leaves","treeLeaves"),Map.entry("minecraft:wool","wool")));
        return Map.copyOf(result);
    }
